/** Functional smoke test of the UI flows (dev server): node eval/scripts/smoke.ts */
import { resolve } from "node:path";
import puppeteer from "puppeteer-core";
import { createServer } from "vite";
const server = await createServer({ root: resolve("."), server: { port: 5193, strictPort: true }, logLevel: "error" });
await server.listen();
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true, args: ["--use-angle=metal", "--enable-gpu", "--autoplay-policy=no-user-gesture-required"] });
const p = await b.newPage(); const errs: string[] = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.setViewport({ width: 1280, height: 900 });
await p.goto("http://localhost:5193/");
const ok = (name: string, v: boolean): void => { console.log(`${v ? "PASS" : "FAIL"} ${name}`); if (!v) process.exitCode = 1; };
await new Promise((r) => setTimeout(r, 1500));
ok("lazy: no model download before a source is chosen", !(await p.evaluate(() => performance.getEntriesByType("resource").some((e) => e.name.includes(".onnx")))));
await p.click("#lang-en");
ok("language switch → English", await p.$eval(".lead", (e) => e.textContent!.startsWith("See what")));
const up = async (sel: string, f: string): Promise<void> => (await p.$(sel) as unknown as { uploadFile(f: string): Promise<void> }).uploadFile(resolve(f));
await up("#file-img", "eval/fixtures/objects/ctl-car.jpg");
await p.waitForFunction(() => document.querySelectorAll("#counts li .v").length > 0, { timeout: 60000 });
await p.waitForFunction(() => document.getElementById("status")!.textContent!.startsWith("Model ready"), { timeout: 30000 }).catch(() => undefined);
ok("status follows language", await p.$eval("#status", (e) => e.textContent!.startsWith("Model ready")));
ok("image → analysis screen, counts shown", await p.$eval("#analysis", (e) => !(e as HTMLElement).hidden));
ok("back/status visible on analysis", await p.$eval(".site-header .back", (e) => getComputedStyle(e).visibility === "visible"));
const facesChecked = (): Promise<boolean> => p.$eval("#faces-on", (e) => (e as HTMLInputElement).checked);
const settingsOpen = (): Promise<boolean> => p.$eval("#settings", (e) => (e as HTMLDetailsElement).open);
const switchShown = (): Promise<boolean> => p.$eval(".switch", (e) => e.checkVisibility());
const height = (): Promise<number> => p.$eval("#settings", (e) => e.getBoundingClientRect().height);
/** Clicks the settings heading and samples the height halfway through and after the 0.3 s transition. */
const toggleSettings = async (): Promise<{ from: number; mid: number; to: number }> => {
  const from = await height(); await p.click("#settings summary");
  await new Promise((r) => setTimeout(r, 150)); const mid = await height();
  await new Promise((r) => setTimeout(r, 350)); return { from, mid, to: await height() };
};
const between = (h: { from: number; mid: number; to: number }): boolean => h.mid > Math.min(h.from, h.to) && h.mid < Math.max(h.from, h.to);
ok("settings collapsed by default", !(await settingsOpen()) && !(await switchShown()));
ok("photo with a person: faces switch on automatically", await facesChecked());
const rows = (): Promise<{ sub: boolean; n: string; total: string; now: string }[]> => p.$$eval("#counts li", (l) => l.map((e) => {
  const [n, total, now] = [...e.querySelectorAll("span")].map((s) => s.textContent!);
  return { sub: e.classList.contains("sub"), n, total, now };
}));
await p.waitForFunction(() => document.querySelector("#counts li.sub"), { timeout: 30000 }).catch(() => undefined);
const car = await rows(), sum = car.find((r) => r.n === "Person (total)"), parts = car.filter((r) => r.sub);
ok("no separate people panel", (await p.$("#faces")) === null);
ok("counts break persons down by expression, summing to the current frame", !!sum && parts.length > 0 && parts.reduce((s, r) => s + +r.now, 0) === +sum.now && parts.every((r) => r.total === ""));
console.log(car.map((r) => `     ${r.sub ? "- " : ""}${r.n} | ${r.total} | ${r.now}`).join("\n"));
await up("#file-img", "eval/fixtures/objects/ctl-person.jpg");
await p.waitForFunction(() => /^Person \(/.test(document.querySelector("#counts .n")?.textContent ?? ""), { timeout: 30000 }).catch(() => undefined);
const one = await rows();
ok("one person with one result: a single row", one.length === 1 && !one[0].sub && /^Person \((?!total)/.test(one[0].n));
console.log("     " + JSON.stringify(one));
await up("#file-img", "eval/fixtures/objects/ctl-cup.jpg");
await p.waitForFunction(() => document.querySelector("#counts .n")?.textContent === "Cup", { timeout: 30000 });
await new Promise((r) => setTimeout(r, 1000));
ok("photo without a person: faces stay off", !(await facesChecked()));
const opening = await toggleSettings();
ok("settings expand", (await settingsOpen()) && (await switchShown()));
ok("opening is animated", between(opening));
await p.click(".switch"); ok("faces switch on by hand", await facesChecked());
await p.click(".switch"); ok("faces switch off by hand", !(await facesChecked()));
const closing = await toggleSettings();
ok("settings collapse", !(await settingsOpen()) && !(await switchShown()));
ok("closing is animated", between(closing));
await up("#file-img", "eval/fixtures/objects/ctl-car.jpg");
await p.waitForFunction(() => [...document.querySelectorAll("#counts .n")].some((e) => e.textContent === "Car"), { timeout: 30000 });
const box = await p.$eval(".counts-box", (e) => ({ h: e.getBoundingClientRect().height, scroll: getComputedStyle(e).overflowY }));
ok("counts box is five rows high and scrolls", box.h === 216 && box.scroll === "auto");
const order = await p.$$eval(".right h2, .right button", (els) => els.map((e) => ((e.querySelector("[data-i18n]") ?? e) as HTMLElement).dataset.i18n));
ok("right column order", order.join() === "set.title,counts.title,sug.title,cmp.open,tm.open");
ok("suggestion: best plus two alternatives", (await p.$$eval("#scene .best", (e) => e.length)) === 1 && (await p.$$eval("#scene .alt", (e) => e.length)) === 2);
await p.click("#open-cmp");
const chosen = (): Promise<string[]> => p.$$eval("#cmp-scenes button.on", (b) => b.map((e) => (e as HTMLElement).dataset.scene!));
const likely = await p.$eval("#cmp-scenes button.likely", (e) => (e as HTMLElement).dataset.scene!);
ok("comparison opens with eight scenes, most likely preselected", (await p.$$eval("#cmp-scenes button", (b) => b.length)) === 8 && (await chosen()).join() === likely);
const other = likely === "kitchen" ? "office" : "kitchen";
const bars = (): Promise<string> => p.$eval("#compare", (e) => e.innerHTML);
const likelyBars = await bars();
await p.click(`#cmp-scenes button[data-scene="${other}"]`); await new Promise((r) => setTimeout(r, 600));
ok("another scene can be chosen and compared", (await chosen()).join() === other && (await bars()) !== likelyBars);
ok("comparison has one explanation line", (await p.$$eval("#compare .span-all", (e) => e.length)) === 1);
await p.keyboard.press("Escape"); ok("comparison closes on Escape", await p.$eval("#cmp", (e) => (e as HTMLElement).hidden));
await p.click("#open-tm"); await new Promise((r) => setTimeout(r, 500));
ok("treemap opens with cells", await p.$$eval(".cell", (c) => c.length > 0));
await p.keyboard.press("Escape"); ok("treemap closes on Escape", await p.$eval("#tm", (e) => (e as HTMLElement).hidden));
await p.click("#back-home");
ok("back → home, back link hidden", await p.$eval(".site-header .back", (e) => getComputedStyle(e).visibility === "hidden") && await p.$eval("#home", (e) => !(e as HTMLElement).hidden));
await up("#file-vid", "eval/.out/moving_car.mp4");
await p.waitForFunction(() => { const v = document.getElementById("vid") as HTMLVideoElement; return !v.paused && v.currentTime > 1; }, { timeout: 20000 });
const play = (): Promise<string> => p.$eval("#play", (e) => `${(e.querySelector(".icon") as HTMLElement).dataset.icon} ${e.textContent}`);
ok("icons drawn on home, header, settings and controls", await p.$$eval("[data-icon]", (l) => l.length === 10 && l.every((e) => e.querySelector("svg path"))));
ok("playing: pause icon and label", (await play()) === "pause Pause");
ok("video plays, timeline visible", await p.$eval("#seek", (e) => !(e as HTMLElement).hidden));
await p.keyboard.press("Space"); await new Promise((r) => setTimeout(r, 300));
ok("space pauses", await p.$eval("#vid", (v) => (v as HTMLVideoElement).paused));
ok("paused: play icon and label", (await play()) === "play Play");
ok("counts after video", await p.$$eval("#counts li .v", (c) => c.length > 0));
await up("#file-vid", "eval/.out/moving_handheld.mp4");
await p.waitForFunction(() => { const v = document.getElementById("vid") as HTMLVideoElement; return !v.paused && v.currentTime > 0.5; }, { timeout: 20000 });
await p.waitForFunction(() => (document.getElementById("faces-on") as HTMLInputElement).checked, { timeout: 20000 }).catch(() => undefined);
ok("video with people: faces switch on automatically", await facesChecked());
const t0 = await p.$eval("#vid", (v) => (v as HTMLVideoElement).currentTime);
await new Promise((r) => setTimeout(r, 3000));
const alive = await Promise.race([p.$eval("#vid", (v) => (v as HTMLVideoElement).currentTime), new Promise<number>((r) => setTimeout(() => r(-1), 4000))]);
ok("faces on + playing video: page stays responsive", alive > t0 + 2);
ok("faces on + video: persons broken down in counts", await p.waitForFunction(() => [...document.querySelectorAll("#counts .n")].some((e) => /^(Person \(|Not recognized)/.test(e.textContent!)), { timeout: 10000 }).then(() => true, () => false));
if (!(await settingsOpen())) await toggleSettings();
await p.click(".switch");
await new Promise((r) => setTimeout(r, 2000));
ok("switched off by hand: stays off although people are visible", !(await facesChecked()) && (await p.$$eval("#counts li.sub", (e) => e.length)) === 0 && !(await p.$$eval("#counts .n", (l) => l.some((e) => e.textContent!.includes("(")))));
ok("no page errors", errs.length === 0); if (errs.length) console.log(errs);
await b.close(); await server.close();
