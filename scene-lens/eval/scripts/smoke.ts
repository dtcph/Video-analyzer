/** Functional smoke test of the UI flows (dev server): node eval/scripts/smoke.ts */
import { resolve } from "node:path";
import puppeteer from "puppeteer-core";
import { createServer } from "vite";
const server = await createServer({ root: resolve("."), server: { port: 5193, strictPort: true }, logLevel: "error" });
await server.listen();
const b = await puppeteer.launch({ executablePath: "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome", headless: true, args: ["--use-angle=metal", "--enable-gpu", "--autoplay-policy=no-user-gesture-required"] });
const p = await b.newPage(); const errs: string[] = [];
p.on("pageerror", (e) => errs.push(String(e)));
await p.setViewport({ width: 1280, height: 900 });
await p.goto("http://localhost:5193/");
const ok = (name: string, v: boolean): void => { console.log(`${v ? "PASS" : "FAIL"} ${name}`); if (!v) process.exitCode = 1; };
await p.waitForFunction(() => /준비/.test(document.getElementById("status")!.textContent ?? ""), { timeout: 60000 });
await p.click("#lang-en");
ok("language switch → English", await p.$eval(".lead", (e) => e.textContent!.startsWith("See what")));
ok("status follows language", await p.$eval("#status", (e) => e.textContent!.startsWith("Model ready")));
const up = async (sel: string, f: string): Promise<void> => (await p.$(sel) as unknown as { uploadFile(f: string): Promise<void> }).uploadFile(resolve(f));
await up("#file-img", "eval/fixtures/objects/ctl-car.jpg");
await p.waitForFunction(() => document.querySelectorAll("#counts li .v").length > 0, { timeout: 20000 });
ok("image → analysis screen, counts shown", await p.$eval("#analysis", (e) => !(e as HTMLElement).hidden));
ok("back/status visible on analysis", await p.$eval(".site-header .back", (e) => getComputedStyle(e).visibility === "visible"));
await p.click(".switch"); await p.waitForFunction(() => (document.getElementById("faces-on") as HTMLInputElement).checked, { timeout: 30000 });
ok("faces toggle on", true);
await p.click("#open-tm"); await new Promise((r) => setTimeout(r, 500));
ok("treemap opens with cells", await p.$$eval(".cell", (c) => c.length > 0));
await p.keyboard.press("Escape"); ok("treemap closes on Escape", await p.$eval("#tm", (e) => (e as HTMLElement).hidden));
await p.click("#back-home");
ok("back → home, back link hidden", await p.$eval(".site-header .back", (e) => getComputedStyle(e).visibility === "hidden") && await p.$eval("#home", (e) => !(e as HTMLElement).hidden));
await up("#file-vid", "eval/.out/moving_car.mp4");
await p.waitForFunction(() => { const v = document.getElementById("vid") as HTMLVideoElement; return !v.paused && v.currentTime > 1; }, { timeout: 20000 });
ok("video plays, timeline visible", await p.$eval("#seek", (e) => !(e as HTMLElement).hidden));
await p.keyboard.press("Space"); await new Promise((r) => setTimeout(r, 300));
ok("space pauses", await p.$eval("#vid", (v) => (v as HTMLVideoElement).paused));
ok("counts after video", await p.$$eval("#counts li .v", (c) => c.length > 0));
await up("#file-vid", "eval/.out/moving_handheld.mp4");
await p.waitForFunction(() => { const v = document.getElementById("vid") as HTMLVideoElement; return !v.paused && v.currentTime > 0.5; }, { timeout: 20000 });
if (!(await p.$eval("#faces-on", (e) => (e as HTMLInputElement).checked))) await p.click(".switch");
const t0 = await p.$eval("#vid", (v) => (v as HTMLVideoElement).currentTime);
await new Promise((r) => setTimeout(r, 3000));
const alive = await Promise.race([p.$eval("#vid", (v) => (v as HTMLVideoElement).currentTime), new Promise<number>((r) => setTimeout(() => r(-1), 4000))]);
ok("faces on + playing video: page stays responsive", alive > t0 + 2);
ok("faces on + video: people listed", await p.$eval("#faces", (e) => !(e as HTMLElement).hidden));
ok("no page errors", errs.length === 0); if (errs.length) console.log(errs);
await b.close(); await server.close();
